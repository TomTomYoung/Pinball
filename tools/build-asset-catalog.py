#!/usr/bin/env python3
"""Rebuild the machine-readable inventory and file:// compatible preview data."""
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'assets'
png=(OUT/'backgrounds/playfield.png').read_bytes()
width,height=struct.unpack('>II',png[16:24])
assets=[dict(id='playfield',path='backgrounds/playfield.png',group=1,role='物体を焼き込まない盤面背景',format='png',width=width,height=height,transparent=False,source='built-in image_gen',origin=[width/2,height/2],fit='contain or cover with uniform scale; actual generated ratio retained',prompt='backgrounds/PROMPT.md')]
for filename in ['vector-manifest.json','audio-manifest.json']:
    assets.extend(json.loads((OUT/filename).read_text())['assets'])
for asset in assets:
    data=(OUT/asset['path']).read_bytes()
    asset['bytes']=len(data)
    asset['sha256']=hashlib.sha256(data).hexdigest()
catalog=dict(version=1,created='2026-10-16',status='assets complete; game integration pending',board={'width':800,'height':1000},groups=['盤面背景','筐体・外周枠','壁・レール','ボール','フリッパー','バンパー','衝突演出','UI','効果音','BGM'],assets=assets)
serialized=json.dumps(catalog,ensure_ascii=False,indent=2)+'\n'
(OUT/'manifest.json').write_text(serialized)
(OUT/'catalog.js').write_text('// Generated by tools/build-asset-catalog.py; allows direct file:// use.\nwindow.PINBALL_ASSETS = '+serialized.rstrip()+';\n')
print(f'Catalog: {len(assets)} media files, {sum(a["bytes"] for a in assets):,} bytes.')
